create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.admin_users
        where user_id = (select auth.uid())
    );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create or replace function public.register_homepage_visit()
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
    updated_count bigint;
begin
    update public.homepage_visit_stats
    set visit_count = visit_count + 1
    where id = 1
    returning visit_count into updated_count;
    return coalesce(updated_count, 0);
end;
$$;

create or replace function public.get_homepage_visit_count()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
    select coalesce((select visit_count from public.homepage_visit_stats where id = 1), 0);
$$;

revoke all on public.homepage_visit_stats from public, anon, authenticated;
revoke all on function public.register_homepage_visit() from public;
revoke all on function public.get_homepage_visit_count() from public;
grant execute on function public.register_homepage_visit() to anon, authenticated;
grant execute on function public.get_homepage_visit_count() to anon, authenticated;

